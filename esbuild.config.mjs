import esbuild from 'esbuild';
import fs from 'fs';
import process from 'process';

const prod = process.argv[2] === 'production';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD.
Source: https://github.com/your-name/obsidian-life-map
MapLibre GL JS is bundled under its BSD-3-Clause license.
*/
`;

const cssOut = 'styles.css';

function emitCss() {
	let libCss = '';
	try {
		libCss = fs.readFileSync('node_modules/maplibre-gl/dist/maplibre-gl.css', 'utf8');
	} catch (e) {
		console.warn('[life-map] maplibre-gl.css not found, skipping vendor CSS');
	}
	const ownCss = fs.readFileSync('src/styles.css', 'utf8');
	fs.writeFileSync(cssOut, `${libCss}\n\n${ownCss}`);
}

const cssPlugin = {
	name: 'emit-css',
	setup(build) {
		build.onEnd((result) => {
			if (result.errors.length === 0) emitCss();
		});
	},
};

const options = {
	banner: { js: banner },
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/*',
		'@lezer/*',
		'child_process',
		'crypto',
		'fs',
		'http',
		'https',
		'net',
		'os',
		'path',
		'stream',
		'url',
		'util',
		'zlib',
	],
	format: 'cjs',
	target: 'es2018',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	minify: prod,
	outfile: 'main.js',
	define: {
		'process.env.NODE_ENV': JSON.stringify(prod ? 'production' : 'development'),
	},
	plugins: [cssPlugin],
};

if (prod) {
	await esbuild.build(options);
	console.log('[life-map] production build done');
} else {
	const ctx = await esbuild.context(options);
	await ctx.watch();
	console.log('[life-map] watching...');
}
